// Ноты [MIDI, доли], фразы - по строкам. Слов нет: поём названиями нот (до-ре-ми) или на «ля».
// Новую песню сюда - только с проверенной записью мелодии, не по памяти.
const mk = (id, title, bpm, lines, by) => {
  const b = 60 / bpm, notes = [], ph = []; let t = 0;
  for (const line of lines) {
    ph.push(notes.length);
    for (const [m, beats] of line) { notes.push({ m, t: +t.toFixed(3), d: +(beats * b * .92).toFixed(3) }); t += beats * b; }
  }
  return { id, title, by, src: 'builtin', notes, ph };
};
